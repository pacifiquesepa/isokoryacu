export function translate(language: Language, key: MessageKey): string {
  return translations[language][key];
}

const categoryTranslations: Record<
  CategoryKey,
  Record<Language, string>
> = {
  technology: { en: "Technology", fr: "Technologie", rw: "Ikoranabuhanga" },
  fashion: { en: "Fashion", fr: "Mode", rw: "Imideri" },
  home: { en: "Home", fr: "Maison", rw: "Urugo" },
  beauty: { en: "Beauty", fr: "Beauté", rw: "Ubwiza" },
};

export function translateProduct(
  product: Product,
  language: Language,
): { name: string; category: string; badge?: string } {
  const fallback = productTranslations[product.id]?.[language];
  const localizedName =
    language === "fr"
      ? product.nameFr
      : language === "rw"
        ? product.nameRw
        : product.name;
  const localizedBadge =
    language === "fr"
      ? product.badgeFr
      : language === "rw"
        ? product.badgeRw
        : product.badge;
  const defaultCategoryName = categoryTranslations[product.category]?.en;

  return {
    name: localizedName || fallback?.name || product.name,
    category:
        (product.categoryLabel && product.categoryLabel !== defaultCategoryName
          ? product.categoryLabel
          : categoryTranslations[product.category]?.[language]) ||
      product.categoryLabel ||
      product.category,
    badge: localizedBadge || fallback?.badge || product.badge || undefined,
  };
}

export function formatMoney(amount: number, language: Language): string {
  const locale = language === "fr" ? "fr-RW" : "en-RW";
  return `${amount.toLocaleString(locale)} RWF`;
}
